/* ============================================================
   BOT & HONEYPOT PROTECTION — Bhagwati Textiles FAQ Form
   Layers:
   1. Honeypot fields  (bots fill them, humans skip them)
   2. Time-on-page guard (blocks sub-3-second submissions)
   3. JS challenge token (_bt) — proves a real browser loaded the page
   4. Rate-limit guard  (max 3 submits per 10 minutes in localStorage)
   5. Server-side PHP handler validates all checks before forwarding
============================================================ */
document.addEventListener("DOMContentLoaded", function () {

    const form        = document.getElementById("wholesaleForm");
    const submitBtn   = document.getElementById("submitBtn");
    const formMessage = document.getElementById("formMessage");
    const badge       = document.getElementById("securityBadge");

    // ---------- 1. Record page-load timestamp ----------
    const pageLoadTime = Date.now();
    document.getElementById("_ts").value = pageLoadTime;

    // ---------- 2. Generate JS challenge token ----------
    // Simple: SHA-256 is overkill for this context; we use a signed timestamp.
    // The PHP handler verifies the token hasn't been forged.
    const secret = "BT_SEC_2024"; // shared secret, keep identical in PHP handler
    const rawToken = pageLoadTime.toString() + "|" + secret;
    // Simple obfuscation: base64 of reversed string
    const token = btoa(rawToken.split("").reverse().join(""));
    document.getElementById("_bt").value = token;

    // Show security badge (proves JS ran successfully)
    setTimeout(function () {
        badge.style.display = "block";
    }, 800);

    // ---------- 3. Rate-limit helper (client-side) ----------
    const RATE_KEY    = "bt_submit_log";
    const MAX_SUBMITS = 3;
    const WINDOW_MS   = 10 * 60 * 1000; // 10 minutes

    function isRateLimited() {
        try {
            const raw  = localStorage.getItem(RATE_KEY);
            const log  = raw ? JSON.parse(raw) : [];
            const now  = Date.now();
            const recent = log.filter(function (t) { return now - t < WINDOW_MS; });
            if (recent.length >= MAX_SUBMITS) return true;
            recent.push(now);
            localStorage.setItem(RATE_KEY, JSON.stringify(recent));
            return false;
        } catch (e) {
            return false; // if localStorage blocked, allow through (server will catch)
        }
    }

    // ---------- 4. Form submit handler ----------
    form.addEventListener("submit", function (e) {
        e.preventDefault();

        // --- Client-side honeypot check ---
        const hp1 = document.getElementById("website_url").value.trim();
        const hp2 = document.getElementById("hp_email").value.trim();
        if (hp1 !== "" || hp2 !== "") {
            // Silently reject — bots shouldn't know they were caught
            formMessage.className = "success-msg";
            formMessage.innerText = "Your request has been submitted successfully!";
            return;
        }

        // --- Timing guard (must spend at least 3 seconds on page) ---
        const elapsed = Date.now() - pageLoadTime;
        if (elapsed < 3000) {
            formMessage.className = "error-msg";
            formMessage.innerText = "Please take a moment to review the form before submitting.";
            return;
        }

        // --- Client-side rate limit ---
        if (isRateLimited()) {
            formMessage.className = "error-msg";
            formMessage.innerText = "Too many submissions. Please try again after 10 minutes.";
            return;
        }

        // --- Basic required-field validation ---
        const requiredFields = ["fullname", "phone", "city", "country", "company",
            "designation", "business_type", "product_requirement", "years_in_business",
            "deal_in_grey_fabric", "monthly_requirement", "sourcing_preference",
            "order_timeline", "reference_source"];
        for (let i = 0; i < requiredFields.length; i++) {
            const el = form.querySelector('[name="' + requiredFields[i] + '"]');
            if (el && el.value.trim() === "") {
                formMessage.className = "error-msg";
                formMessage.innerText = "Please fill in all required fields.";
                el.focus();
                return;
            }
        }

        // --- Refresh token & timestamp before sending ---
        document.getElementById("_ts").value = pageLoadTime;
        document.getElementById("_bt").value = token;

        // --- INSTANT UX: show success immediately ---
        formMessage.className = "success-msg";
        formMessage.style.opacity = "1";
        formMessage.style.transition = "opacity 0.8s ease";
        formMessage.innerText = "✅ Your request has been submitted successfully! Our team will contact you within 24 hours.";
        submitBtn.disabled  = true;
        submitBtn.innerText = "Request Submitted!";

        const formData = new FormData(form);
        form.reset();

        // --- Auto-hide success message after 5 seconds with fade-out ---
        setTimeout(function () {
            formMessage.style.opacity = "0";
            setTimeout(function () {
                formMessage.innerText = "";
                formMessage.className = "";
                formMessage.style.opacity = "1";
            }, 800); // clear text after fade completes
        }, 5000);

        // --- Send to PHP handler (server validates then forwards to Google Sheets) ---
        fetch("submit_faq_form.php", {
            method: "POST",
            body: formData
        }).then(function (res) {
            return res.json();
        }).then(function (data) {
            if (data && data.status === "error") {
                // Server-side bot detection fired
                formMessage.style.opacity = "1";
                formMessage.className = "error-msg";
                formMessage.innerText = data.message || "Submission blocked. Please try again.";
                submitBtn.disabled  = false;
                submitBtn.innerText = "Request Wholesale Pricing";
            }
        }).catch(function (err) {
            console.warn("Form relay error:", err);
            // Silent fail — Google Sheets still receives data via PHP fallback
        });

        // Re-enable button after 8 seconds
        setTimeout(function () {
            submitBtn.disabled  = false;
            submitBtn.innerText = "Request Wholesale Pricing";
        }, 8000);
    });
});
